    #[test]
    fn test_pattern_node_access() {
        let node = PATTERN_NODES[0];

        // Test BD access
        assert_eq!(node.get_bd(0), 255);
        assert_eq!(node.get_bd(1), 0);

        // Test SD access (bytes 32-63)
        assert_eq!(node.get_sd(0), 36);

        // Test HH access (bytes 64-95)
        assert_eq!(node.get_hh(0), 170);
    }

    #[test]
    fn test_drum_map_indexing() {
        // Verify drum map references valid node indices
        for row in DRUM_MAP.iter() {
            for &node_id in row.iter() {
                assert!(node_id < 25, "Node ID {} is out of range", node_id);
            }
        }
    }

    #[test]
    fn test_all_nodes_accessible() {
        // Verify all 25 nodes exist
        assert_eq!(PATTERN_NODES.len(), 25);

        // Verify each has correct size
        for (i, node) in PATTERN_NODES.iter().enumerate() {
            assert_eq!(node.data.len(), 96, "Node {} has incorrect data length", i);
        }
    }
