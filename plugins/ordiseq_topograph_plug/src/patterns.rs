/// A pattern node contains 96 bytes of data:
/// - Bytes 0-31: BD (bass drum) levels for steps 0-31
/// - Bytes 32-63: SD (snare drum) levels for steps 0-31
/// - Bytes 64-95: HH (hi-hat) levels for steps 0-31
///
/// Each value is 0-255 representing the "hit level" at that step.
/// These values are interpolated and compared against density thresholds.
#[derive(Clone, Copy)]
pub struct PatternNode {
    pub data: [u8; 96],
}

impl PatternNode {
    const STEPS_PER_PATTERN: usize = 32;

    /// Get bass drum level for a specific step (0-31)
    pub fn get_bd(&self, step: usize) -> u8 {
        self.data[step]
    }

    /// Get snare drum level for a specific step (0-31)
    pub fn get_sd(&self, step: usize) -> u8 {
        self.data[Self::STEPS_PER_PATTERN + step]
    }

    /// Get hi-hat level for a specific step (0-31)
    pub fn get_hh(&self, step: usize) -> u8 {
        self.data[2 * Self::STEPS_PER_PATTERN + step]
    }
}

